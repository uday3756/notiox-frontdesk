-- ---------------------------------------------------------------------------
-- Host allow-list helper view (custom domains marked verified)
-- Application layer also reads ALLOWED_HOSTS env + owners.custom_domain
-- ---------------------------------------------------------------------------
create or replace view public.verified_owner_hosts as
select
  id as owner_id,
  lower(custom_domain) as host,
  brand_name
from public.owners
where custom_domain is not null
  and custom_domain_verified = true;

