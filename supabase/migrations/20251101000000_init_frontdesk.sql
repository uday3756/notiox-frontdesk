-- NotioX Front Desk — initial schema + RLS
-- Owner-scoped: each owner only sees their own rows.
-- Clients/students remain on NotioX (notiolive.com); Front Desk generates codes only.

-- Extensions
create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------------
-- owners
-- ---------------------------------------------------------------------------
create table if not exists public.owners (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'other'
    check (role in ('coach', 'adhd_trainer', 'mental_health_doctor', 'ugc_creator', 'other')),
  brand_name text,
  brand_logo_url text,
  custom_domain text unique,
  custom_domain_verified boolean not null default false,
  stripe_customer_id text,
  stripe_account_id text,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists owners_email_idx on public.owners (email);
create index if not exists owners_custom_domain_idx on public.owners (custom_domain)
  where custom_domain is not null;

-- ---------------------------------------------------------------------------
-- owner_codes — promo / referral codes generated by Front Desk owners
-- Clients ENTER these in NotioX (https://www.notiolive.com), not here.
-- ---------------------------------------------------------------------------
create table if not exists public.owner_codes (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.owners (id) on delete cascade,
  code text not null,
  label text,
  code_type text not null default 'promo'
    check (code_type in ('promo', 'referral', 'invite')),
  max_uses integer,
  use_count integer not null default 0,
  active boolean not null default true,
  expires_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, code)
);

create index if not exists owner_codes_owner_id_idx on public.owner_codes (owner_id);
create index if not exists owner_codes_code_idx on public.owner_codes (code);

-- ---------------------------------------------------------------------------
-- owner_clients — clients linked to an owner (via code redemption / invite)
-- ---------------------------------------------------------------------------
create table if not exists public.owner_clients (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.owners (id) on delete cascade,
  email text not null,
  full_name text,
  status text not null default 'active'
    check (status in ('active', 'inactive', 'invited', 'churned')),
  code_id uuid references public.owner_codes (id) on delete set null,
  notiox_user_id text,
  notes text,
  tags text[] not null default '{}',
  last_active_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, email)
);

create index if not exists owner_clients_owner_id_idx on public.owner_clients (owner_id);
create index if not exists owner_clients_status_idx on public.owner_clients (owner_id, status);

-- ---------------------------------------------------------------------------
-- owner_tasks
-- ---------------------------------------------------------------------------
create table if not exists public.owner_tasks (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.owners (id) on delete cascade,
  title text not null,
  description text,
  due_at timestamptz,
  priority text not null default 'medium'
    check (priority in ('low', 'medium', 'high')),
  status text not null default 'open'
    check (status in ('open', 'in_progress', 'done', 'cancelled')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists owner_tasks_owner_id_idx on public.owner_tasks (owner_id);

-- ---------------------------------------------------------------------------
-- owner_task_assignments — assign one task to one or many clients
-- ---------------------------------------------------------------------------
create table if not exists public.owner_task_assignments (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.owners (id) on delete cascade,
  task_id uuid not null references public.owner_tasks (id) on delete cascade,
  client_id uuid not null references public.owner_clients (id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'in_progress', 'completed', 'skipped')),
  completed_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (task_id, client_id)
);

create index if not exists owner_task_assignments_owner_id_idx
  on public.owner_task_assignments (owner_id);
create index if not exists owner_task_assignments_task_id_idx
  on public.owner_task_assignments (task_id);
create index if not exists owner_task_assignments_client_id_idx
  on public.owner_task_assignments (client_id);

-- ---------------------------------------------------------------------------
-- owner_email_campaigns — Front Desk bulk email (named to avoid NotioX email_campaigns) (subject/body, test send, then send selected/all)
-- ---------------------------------------------------------------------------
create table if not exists public.owner_email_campaigns (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.owners (id) on delete cascade,
  subject text not null,
  body_html text not null,
  body_text text,
  extra_content text,
  status text not null default 'draft'
    check (status in ('draft', 'tested', 'sending', 'sent', 'failed', 'cancelled')),
  recipient_mode text not null default 'selected'
    check (recipient_mode in ('all', 'selected')),
  recipient_client_ids uuid[] not null default '{}',
  test_sent_at timestamptz,
  test_to_email text,
  sent_at timestamptz,
  send_stats jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists owner_email_campaigns_owner_id_idx on public.owner_email_campaigns (owner_id);

-- ---------------------------------------------------------------------------
-- updated_at helper
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists owners_set_updated_at on public.owners;
